#!/usr/bin/env python3
"""HARMONIE - Life With Style: copy the pet assets of Companion Dogs into our mod, under our names.

Owner, 2026-10-23: the Companion Dogs author allowed us to use its model assets
(credit in 42/CREDITS_PETS.txt). Only assets are taken -- the code is ours.
Everything gets an LWSPet_ name so both mods can run on one server.

    python3 tools/import_pets.py <unzipped Companion Dogs>/mods/CompanionDogs/42

Writes: models_X/Skinned/LWSPet_<Breed>.glb, textures/Body/LWSPet_<Breed>.png,
textures/Item_LWSPet_<Breed>.png (icon, from the portrait), sound/LWSPet_*.ogg,
scripts/HARMONIE_LWS_pets_models.txt, scripts/HARMONIE_LWS_pets_sounds.txt.
"""
import os, shutil, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
MEDIA = os.path.join(os.path.dirname(HERE), "42", "media")
sys.path.insert(0, HERE)
from gen_lws import PETS

# their file -> ours
SOUNDS = {
    "CDDogBark1": "LWSPet_Bark1", "CDDogBark2": "LWSPet_Bark2", "CDDogBark3": "LWSPet_Bark3",
    "CDDogWhine1": "LWSPet_Whine1", "CDDogWhine2": "LWSPet_Whine2",
    "CDDogIdle1": "LWSPet_Idle1", "CDDogIdle2": "LWSPet_Idle2",
    "CDDogEat1": "LWSPet_Eat1",
}


def copy(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(src, dst)
    print("copied", os.path.relpath(dst, MEDIA))


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, MEDIA))


def main(src):
    sm = os.path.join(src, "media")
    models = ["/* GENERATED by tools/import_pets.py -- do not edit.",
              "   Life With Style pets: Companion Dogs' dog meshes (used with permission, CREDITS_PETS.txt).",
              "   They are rigged to the vanilla raccoon skeleton and keep their own animations. */",
              "module Base", "{"]
    for p in PETS:
        b = p["breed"]
        copy(os.path.join(sm, "models_X", "Skinned", p["their_mesh"] + ".glb"),
             os.path.join(MEDIA, "models_X", "Skinned", "LWSPet_%s.glb" % b))
        copy(os.path.join(sm, "textures", "Body", p["their_texture"] + ".png"),
             os.path.join(MEDIA, "textures", "Body", "LWSPet_%s.png" % b))
        icon = Image.open(os.path.join(sm, "textures", p["their_portrait"] + ".png")).convert("RGBA")
        icon.resize((128, 128), Image.LANCZOS).save(os.path.join(MEDIA, "textures", "Item_LWSPet_%s.png" % b))
        print("icon", "Item_LWSPet_%s.png" % b)
        models += ["    model LWSPet_%s" % b, "    {",
                   "        mesh = Skinned/LWSPet_%s," % b,
                   "        shader = animalEffect,",
                   "        static = false,",
                   "        animationsMesh = LWSPet_%sAnim," % b,
                   "        attachment head",
                   "        {",
                   "            offset = -0.0106 0.2881 0.0874,",
                   "            rotate = -179.0 -5.0 95.0,",
                   "            bone = Dummy01,",
                   "        }",
                   "    }", "",
                   "    animationsMesh LWSPet_%sAnim" % b, "    {",
                   "        meshFile = Skinned/LWSPet_%s," % b,
                   "        keepMeshAnimations = true,",
                   "    }", ""]
    models.append("}")
    write(os.path.join(MEDIA, "scripts", "HARMONIE_LWS_pets_models.txt"), "\n".join(models) + "\n")
    for theirs, ours in SOUNDS.items():
        copy(os.path.join(sm, "sound", theirs + ".ogg"), os.path.join(MEDIA, "sound", ours + ".ogg"))

    def clips(names, dmin, dmax, vol=None):
        v = "" if vol is None else " volume = %s," % vol
        return ["        clip { file = media/sound/%s.ogg, distanceMin = %d, distanceMax = %d,%s }" % (n, dmin, dmax, v) for n in names]
    snd = ["/* GENERATED by tools/import_pets.py -- do not edit.",
           "   Life With Style pet voices: Companion Dogs' clips (CC0, BigSoundBank / Freesound -- CREDITS_PETS.txt).",
           "   Played on the pet's own emitter only (no world sound: a pet never draws zombies). */",
           "module Base", "{"]
    for name, files, dmin, dmax, vol in (
            ("LWSPetBark", ["LWSPet_Bark1", "LWSPet_Bark2", "LWSPet_Bark3"], 4, 25, None),
            ("LWSPetWhine", ["LWSPet_Whine1", "LWSPet_Whine2"], 2, 15, None),
            ("LWSPetIdle", ["LWSPet_Idle1", "LWSPet_Idle2"], 2, 10, 0.4),
            ("LWSPetHappy", ["LWSPet_Idle1", "LWSPet_Idle2"], 2, 12, 0.9),
            ("LWSPetEat", ["LWSPet_Eat1"], 2, 10, None)):
        snd += ["    sound %s" % name, "    {", "        category = Animal,", "        maxInstancesPerEmitter = 1,"]
        snd += clips(files, dmin, dmax, vol)
        snd += ["    }"]
    snd.append("}")
    write(os.path.join(MEDIA, "scripts", "HARMONIE_LWS_pets_sounds.txt"), "\n".join(snd) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
